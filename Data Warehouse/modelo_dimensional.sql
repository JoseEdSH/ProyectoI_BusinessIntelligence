COMMENT ON COLUMN dw.dim_campania.tipo_descuento IS 'Tipo de descuento de la campaña.';
COMMENT ON COLUMN dw.dim_campania.valor_descuento IS 'Valor del descuento definido para la campaña.';
COMMENT ON COLUMN dw.dim_campania.fecha_inicio IS 'Fecha de inicio de la campaña.';
