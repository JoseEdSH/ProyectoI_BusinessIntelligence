-- ------------------------------------------------------------
-- 2.1 DimTiempo
-- ------------------------------------------------------------
CREATE TABLE dw.dim_tiempo (
    sk_tiempo      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE UNIQUE,
    dia             INTEGER,
    nombre_dia      VARCHAR(20),
    semana          INTEGER,
    mes             INTEGER,
    nombre_mes      VARCHAR(20),
    trimestre       INTEGER,
    anio            INTEGER
);

COMMENT ON TABLE dw.dim_tiempo IS
'Dimensión de tiempo conformada. Se reutiliza con distintos roles: fecha de pedido, fecha prevista, fecha de entrega real y fecha de evento.';

COMMENT ON COLUMN dw.dim_tiempo.sk_tiempo IS 'Llave subrogada de la dimensión de tiempo.';
COMMENT ON COLUMN dw.dim_tiempo.fecha IS 'Fecha calendario representada por la fila.';
COMMENT ON COLUMN dw.dim_tiempo.dia IS 'Número de día del mes.';
COMMENT ON COLUMN dw.dim_tiempo.nombre_dia IS 'Nombre del día de la semana.';
COMMENT ON COLUMN dw.dim_tiempo.semana IS 'Número de semana del año.';
COMMENT ON COLUMN dw.dim_tiempo.mes IS 'Número de mes.';
COMMENT ON COLUMN dw.dim_tiempo.nombre_mes IS 'Nombre del mes.';
COMMENT ON COLUMN dw.dim_tiempo.trimestre IS 'Trimestre calendario, de 1 a 4.';
COMMENT ON COLUMN dw.dim_tiempo.anio IS 'Año calendario.';


-- ------------------------------------------------------------
-- 2.2 DimCliente
-- ------------------------------------------------------------
