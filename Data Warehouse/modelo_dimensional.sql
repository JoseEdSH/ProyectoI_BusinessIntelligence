-- 4. TABLAS DE HECHOS
-- ============================================================

-- ------------------------------------------------------------
-- 4.1 FactPedido
-- Granularidad: una fila por pedido.
-- ------------------------------------------------------------
CREATE TABLE dw.fact_pedido (
    id_pedido             INTEGER PRIMARY KEY,

    sk_tiempo_pedido      INTEGER NOT NULL,
    sk_cliente            INTEGER NOT NULL,
    sk_campania           INTEGER NOT NULL,
    sk_contexto_pedido    INTEGER NOT NULL,

    cantidad_pedidos      INTEGER NOT NULL DEFAULT 1,
    monto_total           NUMERIC(12,2),

    CONSTRAINT fk_fact_pedido_tiempo
        FOREIGN KEY (sk_tiempo_pedido)
        REFERENCES dw.dim_tiempo(sk_tiempo),

    CONSTRAINT fk_fact_pedido_cliente
        FOREIGN KEY (sk_cliente)
        REFERENCES dw.dim_cliente(sk_cliente),

    CONSTRAINT fk_fact_pedido_campania
        FOREIGN KEY (sk_campania)
        REFERENCES dw.dim_campania(sk_campania),

    CONSTRAINT fk_fact_pedido_contexto
        FOREIGN KEY (sk_contexto_pedido)
        REFERENCES dw.dim_contexto_pedido(sk_contexto_pedido),

    CONSTRAINT ck_fact_pedido_cantidad
        CHECK (cantidad_pedidos = 1)
);

COMMENT ON TABLE dw.fact_pedido IS
'Tabla de hechos a nivel de pedido. Permite analizar cantidad de pedidos, monto total, ticket promedio y recurrencia de compra.';

COMMENT ON COLUMN dw.fact_pedido.id_pedido IS 'Dimensión degenerada e identificador del pedido en la fuente.';
COMMENT ON COLUMN dw.fact_pedido.cantidad_pedidos IS 'Medida aditiva con valor constante 1 por fila.';
COMMENT ON COLUMN dw.fact_pedido.monto_total IS 'Monto total del pedido proveniente de public.pedido.monto_total.';


-- ------------------------------------------------------------
-- 4.2 FactDetalleVenta
-- Granularidad: una fila por línea de producto del pedido.
-- ------------------------------------------------------------
CREATE TABLE dw.fact_detalle_venta (
    id_detalle             INTEGER PRIMARY KEY,
    id_pedido              INTEGER NOT NULL,

    sk_tiempo_pedido       INTEGER NOT NULL,
    sk_cliente             INTEGER NOT NULL,
    sk_campania            INTEGER NOT NULL,
    sk_producto            INTEGER NOT NULL,
    sk_contexto_pedido     INTEGER NOT NULL,

    cantidad               INTEGER NOT NULL,
    precio_venta_unitario  NUMERIC(10,2) NOT NULL,
    ingreso_bruto          NUMERIC(12,2) NOT NULL,
    costo_unitario         NUMERIC(10,2),
    costo_total            NUMERIC(12,2),
    margen_bruto           NUMERIC(12,2),

    CONSTRAINT fk_fact_detalle_tiempo
        FOREIGN KEY (sk_tiempo_pedido)
        REFERENCES dw.dim_tiempo(sk_tiempo),

    CONSTRAINT fk_fact_detalle_cliente
        FOREIGN KEY (sk_cliente)
        REFERENCES dw.dim_cliente(sk_cliente),

    CONSTRAINT fk_fact_detalle_campania
        FOREIGN KEY (sk_campania)
        REFERENCES dw.dim_campania(sk_campania),

    CONSTRAINT fk_fact_detalle_producto
        FOREIGN KEY (sk_producto)
        REFERENCES dw.dim_producto(sk_producto),

    CONSTRAINT fk_fact_detalle_contexto
        FOREIGN KEY (sk_contexto_pedido)
        REFERENCES dw.dim_contexto_pedido(sk_contexto_pedido),

    CONSTRAINT ck_fact_detalle_cantidad
        CHECK (cantidad > 0)
);

COMMENT ON TABLE dw.fact_detalle_venta IS
'Tabla de hechos a nivel de línea de pedido. Permite analizar productos, categorías, marcas, unidades, ingresos, costos y margen.';

COMMENT ON COLUMN dw.fact_detalle_venta.id_detalle IS 'Dimensión degenerada e identificador de DetallePedido en la fuente.';
COMMENT ON COLUMN dw.fact_detalle_venta.id_pedido IS 'Identificador degenerado del pedido al que pertenece la línea.';
COMMENT ON COLUMN dw.fact_detalle_venta.ingreso_bruto IS 'Equivale al subtotal de la línea de pedido.';
COMMENT ON COLUMN dw.fact_detalle_venta.costo_total IS 'Medida derivada: cantidad multiplicada por costo_unitario.';
COMMENT ON COLUMN dw.fact_detalle_venta.margen_bruto IS 'Medida derivada: ingreso_bruto menos costo_total.';


-- ------------------------------------------------------------
-- 4.3 FactEnvio
-- Granularidad: una fila por envío.
-- ------------------------------------------------------------
CREATE TABLE dw.fact_envio (
    id_envio                 INTEGER PRIMARY KEY,
    id_pedido                INTEGER NOT NULL UNIQUE,

    sk_tiempo_pedido         INTEGER NOT NULL,
    sk_tiempo_previsto       INTEGER NOT NULL,
    sk_tiempo_entrega_real   INTEGER NOT NULL,

    sk_operador              INTEGER NOT NULL,
    sk_contexto_envio        INTEGER NOT NULL,
    sk_contexto_pedido       INTEGER NOT NULL,

    cantidad_envios          INTEGER NOT NULL DEFAULT 1,
    dias_entrega             INTEGER,
    dias_desviacion          INTEGER,
    entrega_a_tiempo         SMALLINT,

    CONSTRAINT fk_fact_envio_tiempo_pedido
        FOREIGN KEY (sk_tiempo_pedido)
        REFERENCES dw.dim_tiempo(sk_tiempo),

    CONSTRAINT fk_fact_envio_tiempo_previsto
        FOREIGN KEY (sk_tiempo_previsto)
        REFERENCES dw.dim_tiempo(sk_tiempo),

    CONSTRAINT fk_fact_envio_tiempo_real
        FOREIGN KEY (sk_tiempo_entrega_real)
        REFERENCES dw.dim_tiempo(sk_tiempo),

    CONSTRAINT fk_fact_envio_operador
        FOREIGN KEY (sk_operador)
        REFERENCES dw.dim_operador_logistico(sk_operador),

    CONSTRAINT fk_fact_envio_contexto_envio
        FOREIGN KEY (sk_contexto_envio)
        REFERENCES dw.dim_contexto_envio(sk_contexto_envio),

    CONSTRAINT fk_fact_envio_contexto_pedido
        FOREIGN KEY (sk_contexto_pedido)
        REFERENCES dw.dim_contexto_pedido(sk_contexto_pedido),

    CONSTRAINT ck_fact_envio_cantidad
        CHECK (cantidad_envios = 1),

    CONSTRAINT ck_fact_envio_a_tiempo
        CHECK (entrega_a_tiempo IN (0, 1) OR entrega_a_tiempo IS NULL)
);

COMMENT ON TABLE dw.fact_envio IS
'Tabla de hechos a nivel de envío. Permite analizar tiempos de entrega y cumplimiento logístico.';

COMMENT ON COLUMN dw.fact_envio.id_envio IS 'Dimensión degenerada e identificador del envío en la fuente.';
COMMENT ON COLUMN dw.fact_envio.id_pedido IS 'Identificador del pedido asociado. La fuente define un envío por pedido.';
COMMENT ON COLUMN dw.fact_envio.dias_entrega IS 'Días transcurridos entre fecha_pedido y fecha_entrega_real.';
COMMENT ON COLUMN dw.fact_envio.dias_desviacion IS 'Diferencia en días entre fecha_entrega_real y fecha_prevista.';
COMMENT ON COLUMN dw.fact_envio.entrega_a_tiempo IS '1 si la entrega real fue en o antes de la fecha prevista; 0 si fue tardía; NULL si no aplica.';


