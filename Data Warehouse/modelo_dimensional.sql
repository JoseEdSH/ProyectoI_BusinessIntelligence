-- 6. VERIFICACIÓN DE LA IMPLEMENTACIÓN
-- ============================================================

-- 6.1 Deben aparecer 12 tablas en el esquema dw.
SELECT
    table_schema,
    table_name
FROM information_schema.tables
WHERE table_schema = 'dw'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;


-- 6.2 Comprobar que existen 8 dimensiones y 4 tablas de hechos.
SELECT
    COUNT(*) FILTER (WHERE table_name LIKE 'dim_%') AS dimensiones,
    COUNT(*) FILTER (WHERE table_name LIKE 'fact_%') AS hechos,
    COUNT(*) AS total_tablas
FROM information_schema.tables
WHERE table_schema = 'dw'
  AND table_type = 'BASE TABLE';


-- 6.3 Comprobar los miembros técnicos creados.
SELECT 'dim_tiempo' AS tabla, COUNT(*) AS registros FROM dw.dim_tiempo
UNION ALL
SELECT 'dim_cliente', COUNT(*) FROM dw.dim_cliente
UNION ALL
SELECT 'dim_producto', COUNT(*) FROM dw.dim_producto
UNION ALL
